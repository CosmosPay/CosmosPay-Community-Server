import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
// solc-js ships no types; its surface here is one function.
// eslint-disable-next-line @typescript-eslint/no-require-imports
const solc = require('solc') as {
  version(): string;
  compile(input: string): string;
};

/**
 * Compiles every contract under `contracts/` (the deposit-address forwarders
 * and the merchant fee swap router) and writes each one's creation bytecode to
 * its artifact in `src/evm/`, which is committed.
 *
 *   npm run contracts:compile
 *
 * The bytecode is not an implementation detail: every deposit address is
 * `CREATE2(salt, keccak(bytecode ++ args))`, so a different compile is a
 * different set of addresses. An artifact is therefore generated once and
 * reviewed like code, and `payment-forwarder.spec.ts` recompiles each source
 * with the recorded settings and fails if the two disagree. Never edit an
 * artifact by hand; never recompile one to new bytecode while deposit addresses
 * built from the old one still hold money. A changed contract is a NEW contract
 * (as PaymentSplitForwarder is), with an artifact of its own, so the addresses
 * already handed out keep the bytecode they were built from.
 */
const ROOT = join(__dirname, '..');

const CONTRACTS = [
  {
    name: 'PaymentForwarder',
    exportName: 'PAYMENT_FORWARDER_ARTIFACT',
    artifact: 'payment-forwarder.artifact.ts',
  },
  {
    name: 'PaymentSplitForwarder',
    exportName: 'PAYMENT_SPLIT_FORWARDER_ARTIFACT',
    artifact: 'payment-split-forwarder.artifact.ts',
  },
  {
    name: 'MerchantFeeSwapRouter',
    exportName: 'MERCHANT_FEE_SWAP_ROUTER_ARTIFACT',
    artifact: 'merchant-fee-swap-router.artifact.ts',
    // Not a deposit address: the operator deploys it once per aggregator, and
    // the venue checks the deployed code against this bytecode before use.
    note: 'Do not edit: the swap venue checks the deployed router against this bytecode.',
  },
] as const;

const DEPOSIT_ADDRESS_NOTE =
  'Do not edit: every deposit address is derived from this bytecode.';

/** Recorded in each artifact; the spec recompiles with exactly these. */
function settingsFor(name: string) {
  return {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'cancun',
    // No metadata hash: it would bake the source path and comments into the
    // bytecode, and with it into every deposit address.
    metadata: { bytecodeHash: 'none' },
    outputSelection: { '*': { [name]: ['evm.bytecode.object'] } },
  };
}

function compile(contract: (typeof CONTRACTS)[number]): void {
  const sourcePath = join(ROOT, 'contracts', `${contract.name}.sol`);
  const source = readFileSync(sourcePath, 'utf8');
  const settings = settingsFor(contract.name);
  const output = JSON.parse(
    solc.compile(
      JSON.stringify({
        language: 'Solidity',
        sources: { [`${contract.name}.sol`]: { content: source } },
        settings,
      }),
    ),
  ) as {
    errors?: { severity: string; formattedMessage: string }[];
    contracts: Record<
      string,
      Record<string, { evm: { bytecode: { object: string } } }>
    >;
  };
  const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
  if (errors.length > 0) {
    throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
  }
  const bytecode =
    output.contracts[`${contract.name}.sol`][contract.name].evm.bytecode.object;
  const sourceSha256 = createHash('sha256').update(source).digest('hex');

  writeFileSync(
    join(ROOT, 'src', 'evm', contract.artifact),
    `/**
 * GENERATED by \`npm run contracts:compile\` from contracts/${contract.name}.sol.
 * ${'note' in contract ? contract.note : DEPOSIT_ADDRESS_NOTE}
 */
export const ${contract.exportName} = {
  compiler: '${solc.version()}',
  settings: ${JSON.stringify(settings)},
  sourceSha256: '${sourceSha256}',
  bytecode:
    '0x${bytecode}',
} as const;
`,
  );
  console.log(`${contract.name} compiled (${bytecode.length / 2} bytes)`);
}

for (const contract of CONTRACTS) compile(contract);
